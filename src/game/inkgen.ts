import { inkNames, localize, playableCharacters, type GameConfig, type InkNames, type LevelsDef, type LocalizedText, type TableDef, type TableRow } from "./config";
import { averageFormula, averageRoll, formatFormula } from "./dice";
import { inkId, inkText, lookupOrder, tableFormula } from "./tables";

/**
 * The ink a game needs so its stories can run anywhere: skill and resource
 * variables, the character list, a function that loads a character's preset,
 * and a fallback for the engine's check function (no dice: the average roll),
 * so the story also plays in Inky or plain Inkwright. Stories call the check
 * with the skill's name as a string: `check("strength", 12)`. A bilingual game
 * also gets its language variable and text function: `{t("中文", "English")}`.
 */
export function generateInk(config: GameConfig): string {
  const n = inkNames(config);
  const lines: string[] = [
    "// Generated by Inkwright from the game's notes. Do not edit; regenerate.",
    // The rule-system pack's procedures (RPG PRD §5), by a path relative to the game's folder.
    ...(config.systemRules ? [`INCLUDE ${config.systemRules}`] : []),
    "",
    `LIST ${n.characters} = ${config.characters.map((c) => c.id).join(", ")}`,
    `VAR ${n.current} = ${playableCharacters(config)[0]?.id ?? ""}`,
    "",
    "// Skills of the current character (loaded by " + n.select + ")",
    ...config.skills.map((s) => `VAR ${s.id} = 0`),
    "",
    "// Resources",
    ...config.resources.map((r) => `VAR ${r.id} = ${r.initial}`),
    ...(config.items?.length
      ? ["", "// Items: what the character carries (`~ " + n.inventory + " += " + config.items[0].id + "`, `{" + n.inventory + " ? " + config.items[0].id + ": …}`)",
        `LIST ${n.items} = ${config.items.map((i) => i.id).join(", ")}`, `VAR ${n.inventory} = ()`]
      : []),
    "",
    "// Dice: the engine sets these; saved with the state, so back/load/replay roll the same",
    `VAR ${n.seed} = 0`,
    `VAR ${n.rolls} = 0`,
  ];
  const [first, second] = config.languages ?? [];
  if (first !== undefined && second !== undefined) {
    lines.push(
      "",
      `// Text in the story's language: {${n.textFn}("${first}…", "${second}…")}; the play panel switches ${n.langVar}.`,
      `VAR ${n.langVar} = "${first}"`,
      "",
      `=== function ${n.textFn}(${first}, ${second}) ===`,
      `{ ${n.langVar} == "${second}":`,
      `    ~ return ${second}`,
      "}",
      `~ return ${first}`,
    );
  }
  const companions = config.companionResources ?? [];
  if (companions.length > 0) {
    lines.push("", "// Companions");
    for (const c of config.characters) {
      for (const r of companions) lines.push(`VAR ${r.id}_${c.id} = ${c.companion?.[r.id] ?? r.initial}`);
    }
  }
  const party = config.party;
  if (party) {
    const m0 = party.members[0]?.id ?? "id";
    const gear = config.items?.length ? `, ${n.partyGear}_${m0} its gear (\`~ ${n.partyGear}_${m0} += ${config.items[0].id}\`)` : "";
    lines.push("", `// Party: ${party.stats[0] ? `${party.stats[0].id}_${m0} is a member's ${party.stats[0].id}, ` : ""}${n.partyTitle}_${m0} a line the panel shows under the name${gear}.`);
    for (const m of party.members) {
      for (const st of party.stats) lines.push(`VAR ${st.id}_${m.id} = ${m.stats?.[st.id] ?? 0}`);
      lines.push(`VAR ${n.partyTitle}_${m.id} = ""`);
      if (config.items?.length) lines.push(`VAR ${n.partyGear}_${m.id} = (${(m.items ?? []).join(", ")})`);
    }
    if (party.members.length > 0) lines.push(...memberInk(config));
  }
  lines.push(
    "",
    `EXTERNAL ${n.check}(${n.skillParam}, ${n.difficultyParam})`,
    "",
    // The id is a string (0.4.0; engines generated before 0.4.0 took a list item and must be
    // regenerated; the panel's "engine out of date" warning flags them).
    `// Loads a character's preset by id: ${n.select}("${playableCharacters(config)[0]?.id ?? "id"}")`,
    `=== function ${n.select}(${n.whoParam}) ===`,
  );
  for (const c of config.characters) {
    lines.push(`{ ${n.whoParam} == "${c.id}":`, `    ~ ${n.current} = ${c.id}`);
    for (const s of config.skills) lines.push(`    ~ ${s.id} = ${c.skills[s.id] ?? 0}`);
    if (config.items?.length) {
      // Stacks with a count above 0 are carried too; the first carried item of each slot starts equipped.
      const counted = Object.entries(c.counts ?? {}).filter(([, k]) => k > 0).map(([id]) => id);
      const carried = [...new Set([...(c.items ?? []), ...counted])];
      lines.push(`    ~ ${n.inventory} = (${carried.join(", ")})`);
      for (const i of config.items.filter((it) => it.stack)) lines.push(`    ~ ${i.id}${n.stackSuffix} = ${Math.max(0, Math.floor(c.counts?.[i.id] ?? 0))}`);
      if (config.slots?.length) {
        const worn = config.slots.map((sl) => carried.find((id) => config.items?.find((it) => it.id === id)?.slot === sl.id)).filter((id): id is string => id !== undefined);
        lines.push(`    ~ ${n.equipped} = (${worn.join(", ")})`);
      }
    }
    // A character sheet carries its level, resources and statuses (RPG PRD §4.4, §4.6).
    if (config.levels) lines.push(`    ~ ${n.level} = ${Math.max(1, Math.floor(c.level ?? 1))}`);
    for (const [id, v] of Object.entries(c.resources ?? {})) if (config.resources.some((r) => r.id === id)) lines.push(`    ~ ${id} = ${v}`);
    if (config.statuses?.length) {
      lines.push(`    ~ ${n.statusVar} = ""`);
      for (const [id, turns] of Object.entries(c.statuses ?? {})) lines.push(`    ~ ${n.addStatus}("${n.self}", "${id}", ${turns})`);
    }
    lines.push("}");
  }
  lines.push("", `// A skill's current level, by name.`, `=== function ${n.skillValue}(${n.skillParam}) ===`);
  for (const s of config.skills) lines.push(`{ ${n.skillParam} == "${s.id}":`, `    ~ return ${s.id}`, "}");
  lines.push("~ return 0");
  const avg = averageRoll(config.rules);
  lines.push(
    "",
    `// Without the engine there are no dice or modifiers: the average roll (${avg}) decides.`,
    `=== function ${n.check}(${n.skillParam}, ${n.difficultyParam}) ===`,
  );
  // Same grading as dice.ts with the average roll: sum systems (and a chaos bag, with its average
  // token) compare the total with the difficulty; roll-under succeeds when the roll is at or under
  // the skill (difficulty unused).
  // Modifier rules live in the engine, so this fallback ignores them: a story played without the
  // engine is a little more forgiving, never different in structure.
  const level = `${n.skillValue}(${n.skillParam})`;
  const wins = config.rules.kind === "rollUnder" ? `${avg} <= ${level}` : `${level} + ${avg} >= ${n.difficultyParam}`;
  lines.push(`{ ${wins}:`, "    ~ return 3", "}", "~ return 1");

  // Free dice and tables: the engine rolls through one EXTERNAL (and shows the faces); the table
  // lookups are plain ink, so the story reads the same row with or without the engine.
  lines.push(
    "",
    `// Dice outside a check: {${n.roll}("2d6+3")} → the total.`,
    `EXTERNAL ${n.dice}(${n.formulaParam}, ${n.labelParam})`,
    "",
    `=== function ${n.roll}(${n.formulaParam}) ===`,
    `~ return ${n.dice}(${n.formulaParam}, "")`,
  );
  const tables = (config.tables ?? []).map((t) => ({ ...t, rows: t.rows ?? [], formula: tableFormula(t) }));
  const averages = new Map<string, number>();
  for (const t of tables) if (t.formula) averages.set(formatFormula(t.formula), averageFormula(t.formula));
  lines.push("", "// Without the engine the dice are flat: each table's average, 1 for anything else.", `=== function ${n.dice}(${n.formulaParam}, ${n.labelParam}) ===`);
  for (const [text, avg] of averages) lines.push(`{ ${n.formulaParam} == "${text}":`, `    ~ return ${avg}`, "}");
  lines.push("~ return 1");
  if (tables.length > 0) {
    const text = (t: LocalizedText) => (first !== undefined && second !== undefined
      ? `${n.textFn}("${inkText(localize(t, first, ""))}", "${inkText(localize(t, second, ""))}")`
      : `"${inkText(localize(t, "", ""))}"`);
    lines.push(
      "",
      `// Tables: {${n.table}("${tables[0].id}")} rolls and reads a row; ${n.tableRoll}(${n.tableParam}) is the total alone, ${n.tableText}/${n.tableId}(${n.tableParam}, ${n.totalParam}) look a total up.`,
      `=== function ${n.tableRoll}(${n.tableParam}) ===`,
    );
    for (const t of tables) lines.push(`{ ${n.tableParam} == "${t.id}":`, `    ~ return ${n.dice}("${t.formula ? formatFormula(t.formula) : "1d1"}", "${t.id}")`, "}");
    lines.push("~ return 0");
    const lookups: [string, (r: TableRow) => string][] = [[n.tableText, (r) => text(r.text)], [n.tableId, (r) => `"${inkId(r.id)}"`]];
    // The engine looks a total up itself (a chain of branches over every table's rows is slow in ink); these are the fallbacks.
    lines.push(`EXTERNAL ${n.tableText}(${n.tableParam}, ${n.totalParam})`, `EXTERNAL ${n.tableId}(${n.tableParam}, ${n.totalParam})`);
    for (const [fn, value] of lookups) {
      lines.push("", `=== function ${fn}(${n.tableParam}, ${n.totalParam}) ===`);
      for (const t of tables) for (const b of rowBranches(t, n)) lines.push(`{ ${b.cond}:`, `    ~ return ${value(b.row)}`, "}");
      lines.push(`~ return ""`);
    }
    lines.push("", `=== function ${n.table}(${n.tableParam}) ===`, `~ return ${n.tableText}(${n.tableParam}, ${n.tableRoll}(${n.tableParam}))`);
  }

  // Decks: one LIST per deck and a VAR holding the pile; the engine picks the card's position with
  // the same seeded dice (the count goes along as the formula), the ink takes that card out.
  const decks = config.decks ?? [];
  if (decks.length > 0) {
    const first = decks[0];
    lines.push("", `// Decks: ${n.draw}("${first.id}") takes a random card out of the pile (an empty list once none is left); ${n.shuffle} puts them all back; ${n.deckLeft} counts the pile. A hand is a list the story keeps (declared under hands to show as cards): ~ hand += ${n.draw}("${first.id}").`);
    for (const d of decks) {
      const ids = d.cards.map((c) => c.id).join(", ");
      lines.push(`LIST ${d.id} = ${ids}`, `VAR ${d.id}${n.pileSuffix} = (${ids})`);
    }
    lines.push(
      "", "// The k-th card of a list, lowest first.",
      `=== function ${n.nthCard}(${n.stackParam}, ${n.kParam}) ===`,
      `~ temp ${n.tempCard} = LIST_MIN(${n.stackParam})`,
      `{ ${n.kParam} <= 1 or LIST_COUNT(${n.stackParam}) <= 1:`, `    ~ return ${n.tempCard}`, "}",
      `~ return ${n.nthCard}(${n.stackParam} - ${n.tempCard}, ${n.kParam} - 1)`,
      "", `=== function ${n.draw}(${n.deckParam}) ===`,
      // One temp for every deck's branch (ink allows a temp to be declared once in a function): empty when nothing is drawn.
      `~ temp ${n.tempCard} = ()`,
    );
    for (const d of decks) {
      const pile = `${d.id}${n.pileSuffix}`;
      lines.push(
        `{ ${n.deckParam} == "${d.id}" and LIST_COUNT(${pile}) > 0:`,
        `    ~ ${n.tempCard} = ${n.nthCard}(${pile}, ${n.dice}(LIST_COUNT(${pile}), "${d.id}"))`,
        `    ~ ${pile} -= ${n.tempCard}`, `    ~ return ${n.tempCard}`, "}",
      );
    }
    lines.push(`~ return ${n.tempCard}`, "", `=== function ${n.shuffle}(${n.deckParam}) ===`);
    for (const d of decks) lines.push(`{ ${n.deckParam} == "${d.id}":`, `    ~ ${d.id}${n.pileSuffix} = LIST_ALL(${d.id})`, "}");
    lines.push("", `=== function ${n.deckLeft}(${n.deckParam}) ===`);
    for (const d of decks) lines.push(`{ ${n.deckParam} == "${d.id}":`, `    ~ return LIST_COUNT(${d.id}${n.pileSuffix})`, "}");
    lines.push("~ return 0");
    // Card attributes: one function per key, giving the number on a card (0 when it has none).
    const keys = [...new Set(decks.flatMap((d) => d.cards.flatMap((c) => Object.keys(c.attrs ?? {}))))];
    if (keys.length > 0) {
      lines.push("", `// Card attributes: ${n.cardPrefix}${keys[0]}(${n.cardParam}) is that number on the card (0 when it has none).`);
      for (const key of keys) {
        lines.push(`=== function ${n.cardPrefix}${key}(${n.cardParam}) ===`);
        for (const d of decks) {
          for (const c of d.cards) {
            const v = c.attrs?.[key];
            if (v !== undefined) lines.push(`{ ${n.cardParam} == ${c.id}:`, `    ~ return ${v}`, "}");
          }
        }
        lines.push("~ return 0");
      }
    }
  }
  // Hands: the panel shows each as a row of cards; a choice tagged `#play:<hand>` is taken with one
  // of them, which the engine writes into the played VAR first.
  const hands = config.hands ?? [];
  if (hands.length > 0) {
    lines.push("", `// Hands: shown as cards in the panel; the story fills them (~ ${hands[0].id} += ${n.draw}("…")). A choice tagged #play:${hands[0].id} puts the card the player picked into ${n.played} before the choice runs: ~ ${hands[0].id} -= ${n.played}.`);
    for (const h of hands) lines.push(`VAR ${h.id} = ()`);
    lines.push(`VAR ${n.played} = ()`);
  } else if (config.items?.length) {
    // #use: the thing the player picks from what is carried goes into the played VAR, as a card does.
    lines.push("", `// A choice tagged #use is taken with something carried, written into ${n.played} first: { ${n.played} == ${config.items[0].id}: … }.`, `VAR ${n.played} = ()`);
  }
  if (config.turn) {
    lines.push("", `// Rounds and phases, shown on the HUD; the story moves them (~ ${config.turn.round} += 1, ~ ${config.turn.phase} = "${config.turn.phases[0]?.id ?? ""}").`,
      `VAR ${config.turn.round} = 1`, `VAR ${config.turn.phase} = "${config.turn.phases[0]?.id ?? ""}"`);
  }
  // Map: the places as a LIST, where the player is, which places are revealed, and each token's place.
  const map = config.map;
  if (map && map.places.length > 0) {
    const shown = map.places.filter((p) => !p.hidden).map((p) => p.id);
    lines.push("", `// Map: ${n.here} is where the player stands (~ ${n.here} = ${map.places[0].id}), ${n.revealed} the places shown (~ ${n.revealed} += …); a token's place is its own VAR (an empty list keeps it off the map).`);
    lines.push(`LIST ${n.places} = ${map.places.map((p) => p.id).join(", ")}`);
    lines.push(`VAR ${n.here} = (${shown[0] ?? ""})`);
    lines.push(`VAR ${n.revealed} = (${shown.join(", ")})`);
    for (const t of map.tokens ?? []) lines.push(`VAR ${t.id}${n.atSuffix} = (${t.at ?? ""})`);
  }
  const dungeon = config.dungeon;
  if (dungeon) {
    // The generator is handed the resolved config (shapes read from `from` are in), but the comment must not name a shape that is not there.
    const first = dungeon.shapes[0]?.id ?? "<shape id>";
    lines.push(
      "",
      `// Growing dungeon: ${n.dungeonVar} holds the layout (rooms and used doors) as text, ${n.dungeonRoom} the room the party is in.`,
      `// ${n.beginDungeon}("${first}") draws the first room; ${n.addRoom}("${first}", room, door) hangs a room of that shape on the door-th free door of a room`,
      `// (room 0 = any room) and returns its number, or 0 when the door led into a wall; ${n.markRoom}(room, "text") writes a note on a room.`,
      `// ${n.dungeonDoors}(${n.dungeonVar}, room) counts the free doors left (room 0 = the whole dungeon), ${n.dungeonRooms}(${n.dungeonVar}) the rooms, ${n.dungeonShape}/${n.dungeonCorridor}(${n.dungeonVar}, room) read a room.`,
      `// ${n.secretRoom}("${first}", room) finds a secret door on a wall of a room and hangs a room behind it; ${n.dungeonSteps}(${n.dungeonVar}, from, to) counts the rooms walked into on the shortest way,`,
      `// ${n.dungeonNearest}(${n.dungeonVar}, from) is the nearest room with a free door (0 when none is left); ${n.dungeonVia}(${n.dungeonVar}, from, to, k) the k-th room walked into on the way (0 past the end).`,
      `// Room notes for what the map does not hold: ${n.setRoomNote}(room, "field", value), ${n.roomNote}(room, "field") (a number, or text; "" when unset).`,
      `VAR ${n.notesVar} = ""`,
      `VAR ${n.dungeonVar} = ""`,
      `VAR ${n.dungeonRoom} = 0`,
      `EXTERNAL ${n.dungeonStart}(${n.shapeParam})`,
      `EXTERNAL ${n.dungeonAdd}(${n.layoutParam}, ${n.shapeParam}, ${n.roomParam}, ${n.doorParam})`,
      `EXTERNAL ${n.dungeonRooms}(${n.layoutParam})`,
      `EXTERNAL ${n.dungeonDoors}(${n.layoutParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonMark}(${n.layoutParam}, ${n.roomParam}, ${n.markParam})`,
      `EXTERNAL ${n.dungeonShape}(${n.layoutParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonCorridor}(${n.layoutParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonSecret}(${n.layoutParam}, ${n.shapeParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonSteps}(${n.layoutParam}, ${n.roomParam}, ${n.toParam})`,
      `EXTERNAL ${n.dungeonNearest}(${n.layoutParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonVia}(${n.layoutParam}, ${n.roomParam}, ${n.toParam}, ${n.kParam2})`,
      `EXTERNAL ${n.noteGet}(${n.notesParam}, ${n.roomParam}, ${n.fieldParam})`,
      `EXTERNAL ${n.noteSet}(${n.notesParam}, ${n.roomParam}, ${n.fieldParam}, ${n.valueParam})`,
      "",
      "// Without the engine nothing grows: no rooms, no doors left.",
      `=== function ${n.dungeonStart}(${n.shapeParam}) ===`, `~ return ""`,
      `=== function ${n.dungeonAdd}(${n.layoutParam}, ${n.shapeParam}, ${n.roomParam}, ${n.doorParam}) ===`, `~ return ${n.layoutParam}`,
      `=== function ${n.dungeonRooms}(${n.layoutParam}) ===`, "~ return 0",
      `=== function ${n.dungeonDoors}(${n.layoutParam}, ${n.roomParam}) ===`, "~ return 0",
      `=== function ${n.dungeonMark}(${n.layoutParam}, ${n.roomParam}, ${n.markParam}) ===`, `~ return ${n.layoutParam}`,
      `=== function ${n.dungeonShape}(${n.layoutParam}, ${n.roomParam}) ===`, `~ return ""`,
      `=== function ${n.dungeonCorridor}(${n.layoutParam}, ${n.roomParam}) ===`, "~ return 0",
      `=== function ${n.dungeonSecret}(${n.layoutParam}, ${n.shapeParam}, ${n.roomParam}) ===`, `~ return ${n.layoutParam}`,
      // No dungeon, no way between rooms: -1, as the engine says for rooms it cannot join.
      `=== function ${n.dungeonSteps}(${n.layoutParam}, ${n.roomParam}, ${n.toParam}) ===`, "~ return -1",
      `=== function ${n.dungeonNearest}(${n.layoutParam}, ${n.roomParam}) ===`, "~ return 0",
      `=== function ${n.dungeonVia}(${n.layoutParam}, ${n.roomParam}, ${n.toParam}, ${n.kParam2}) ===`, "~ return 0",
      "// Without the engine notes are not kept.",
      `=== function ${n.noteGet}(${n.notesParam}, ${n.roomParam}, ${n.fieldParam}) ===`, `~ return ""`,
      `=== function ${n.noteSet}(${n.notesParam}, ${n.roomParam}, ${n.fieldParam}, ${n.valueParam}) ===`, `~ return ${n.notesParam}`,
      "",
      `=== function ${n.beginDungeon}(${n.shapeParam}) ===`,
      `~ ${n.dungeonVar} = ${n.dungeonStart}(${n.shapeParam})`,
      `~ ${n.dungeonRoom} = ${n.dungeonRooms}(${n.dungeonVar})`,
      `~ return ${n.dungeonRoom}`,
      "",
      `=== function ${n.addRoom}(${n.shapeParam}, ${n.roomParam}, ${n.doorParam}) ===`,
      `~ temp ${n.tempBefore} = ${n.dungeonRooms}(${n.dungeonVar})`,
      `~ ${n.dungeonVar} = ${n.dungeonAdd}(${n.dungeonVar}, ${n.shapeParam}, ${n.roomParam}, ${n.doorParam})`,
      `{ ${n.dungeonRooms}(${n.dungeonVar}) > ${n.tempBefore}:`, `    ~ return ${n.dungeonRooms}(${n.dungeonVar})`, "}",
      "~ return 0",
      "",
      `=== function ${n.markRoom}(${n.roomParam}, ${n.markParam}) ===`,
      `~ ${n.dungeonVar} = ${n.dungeonMark}(${n.dungeonVar}, ${n.roomParam}, ${n.markParam})`,
      "",
      `=== function ${n.roomNote}(${n.roomParam}, ${n.fieldParam}) ===`,
      `~ return ${n.noteGet}(${n.notesVar}, ${n.roomParam}, ${n.fieldParam})`,
      "",
      `=== function ${n.setRoomNote}(${n.roomParam}, ${n.fieldParam}, ${n.valueParam}) ===`,
      `~ ${n.notesVar} = ${n.noteSet}(${n.notesVar}, ${n.roomParam}, ${n.fieldParam}, ${n.valueParam})`,
      "",
      `=== function ${n.secretRoom}(${n.shapeParam}, ${n.roomParam}) ===`,
      `~ temp ${n.tempBefore} = ${n.dungeonRooms}(${n.dungeonVar})`,
      `~ ${n.dungeonVar} = ${n.dungeonSecret}(${n.dungeonVar}, ${n.shapeParam}, ${n.roomParam})`,
      `{ ${n.dungeonRooms}(${n.dungeonVar}) > ${n.tempBefore}:`, `    ~ return ${n.dungeonRooms}(${n.dungeonVar})`, "}",
      "~ return 0",
    );
  }
  if (config.records?.length) lines.push(...recordInk(config));
  if (config.items?.some((i) => i.stack)) lines.push(...stackInk(config));
  if (config.slots?.length && config.items?.length) lines.push(...slotInk(config));
  if (config.statuses?.length) lines.push(...statusInk(config));
  if (config.levels) lines.push(...levelInk(config));
  if (config.kinds?.length) lines.push(...entityInk(config), ...spawnRowInk(config));
  return lines.join("\n") + "\n";
}

/**
 * A table's rows as branches of a lookup on (table name, total), each to be closed by a return, in the order they
 * must be tested: rows with ranges ascending (`total <= hi`); without, the total is the row number. The last row
 * catches the rest.
 */
function rowBranches(t: TableDef, n: InkNames): { cond: string; row: TableRow }[] {
  return lookupOrder(t).map((b) => {
    const cond = b.eq !== undefined ? ` and ${n.totalParam} == ${b.eq}` : b.le !== undefined ? ` and ${n.totalParam} <= ${b.le}` : "";
    return { cond: `${n.tableParam} == "${t.id}"${cond}`, row: b.row };
  });
}

/**
 * Party reads the engine does (RPG PRD §4.5): `member_get(who, "var")` and `party_count("var", value)`, pure and
 * lookahead-safe. An ink switch per member costs some 35 steps a call against 10 through the engine, and stories
 * that ask about members in every choice's text call them thousands of times a turn. The fallbacks (no engine)
 * know what the generator declares per member (stats, title, gear); variables the story adds read as 0 there.
 */
function memberInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const party = config.party!;
  const who = n.memberParam, v = n.varNameParam, m = n.matchParam, c = n.tempMatches;
  const lines = [
    "",
    `// ${n.memberGet}(1, "${party.stats[0]?.id ?? "life"}") or ${n.memberGet}("${party.members[0].id}", …) reads <var>_<member> (any variable the story declares per member too); ${n.partyCount}("<var>", value) counts the members whose variable equals value. Done by the engine: far cheaper than a switch in ink.`,
    `EXTERNAL ${n.memberGet}(${who}, ${v})`,
    `EXTERNAL ${n.partyCount}(${v}, ${m})`,
    `=== function ${n.memberGet}(${who}, ${v}) ===`,
  ];
  // The variables the generator declares per member: the stats, the title line and (with items) the gear.
  const own = [...party.stats.map((st) => st.id), n.partyTitle, ...(config.items?.length ? [n.partyGear] : [])];
  party.members.forEach((mb, i) => {
    lines.push(`{ ${who} == ${i + 1} or ${who} == "${mb.id}":`);
    for (const name of own) lines.push(`    { ${v} == "${name}":`, `        ~ return ${name}_${mb.id}`, "    }");
    lines.push("    ~ return 0", "}");
  });
  // Nobody: the zero of the variable's type, as the engine gives it.
  lines.push(`{ ${v} == "${n.partyTitle}":`, `    ~ return ""`, "}");
  if (config.items?.length) lines.push(`{ ${v} == "${n.partyGear}":`, "    ~ return ()", "}");
  lines.push("~ return 0", "", `=== function ${n.partyCount}(${v}, ${m}) ===`, `~ temp ${c} = 0`);
  for (const name of own) {
    lines.push(`{ ${v} == "${name}":`);
    for (const mb of party.members) lines.push(`    { ${name}_${mb.id} == ${m}:`, `        ~ ${c} = ${c} + 1`, "    }");
    lines.push("}");
  }
  lines.push(`~ return ${c}`);
  return lines;
}

/**
 * The party as fixed entities (RPG PRD §4.1, "party is a kind with fixed members"): branches for the entity
 * wrappers. A member id reads and writes its `<stat>_<id>` VARs; `despawn` sets the `present` stat to 0 (no-op
 * without one); the kind name `party` (InkNames.partyKind) counts and picks the standing members (present and not
 * down, where those stats are set), in the members' order; ties pick the first. Empty without a party.
 */
function partyEntity(config: GameConfig) {
  const n = inkNames(config);
  const party = config.party;
  const none = { stat: [], setStat: [], despawn: [], alive: [], pick: [], nth: [], name: [] } as Record<string, string[]>;
  if (!party || party.members.length === 0) return none;
  const k = n.kindParam, w = n.entityParam, st = n.statParam, a = n.amountParam, h = n.howParam, c = n.tempPickNo, best = n.tempEntity;
  const pk = `"${n.partyKind}"`;
  const [first, second] = config.languages ?? [];
  const esc = (x: string) => x.replace(/["{}]/g, "").replace(/\s+/g, " ");
  const name = (t: LocalizedText | undefined, id: string) => first !== undefined && second !== undefined
    ? `${n.textFn}("${esc(localize(t, first, id))}", "${esc(localize(t, second, id))}")`
    : `"${esc(localize(t, "", id))}"`;
  const members = party.members.map((m) => m.id);
  const standing = (m: string) => [party.present, party.down].filter((x): x is string => x !== undefined).map((x) => `${x}_${m} > 0`).join(" and ") || "true";
  const byMember = (body: (m: string) => string[]) => members.flatMap((m) => [`{ ${w} == "${m}":`, ...body(m).map((l) => `    ${l}`), "}"]);
  const byStat = (m: string, body: (v: string) => string) => party.stats.flatMap((s) => [`{ ${st} == "${s.id}":`, `    ${body(`${s.id}_${m}`)}`, "}"]);
  // The k-th standing member, counting in `c`.
  const nth = (target: string) => [`~ ${c} = 0`, ...members.flatMap((m) => [`{ ${standing(m)}:`, `    ~ ${c} = ${c} + 1`, `    { ${c} == ${target}:`, `        ~ return "${m}"`, "    }", "}"])];
  const count = [`~ ${c} = 0`, ...members.flatMap((m) => [`{ ${standing(m)}:`, `    ~ ${c} = ${c} + 1`, "}"])];
  const extreme = (dir: "lowest" | "highest") => party.stats.flatMap((s) => [
    `{ ${h} == "${dir}:${s.id}":`,
    `    ~ ${best} = ""`,
    ...members.flatMap((m) => [`    { ${standing(m)} and (${best} == "" or ${s.id}_${m} ${dir === "lowest" ? "<" : ">"} ${n.stat}(${best}, "${s.id}")):`, `        ~ ${best} = "${m}"`, "    }"]),
    `    ~ return ${best}`,
    "}",
  ]);
  const inParty = (body: string[]) => [`{ ${k} == ${pk}:`, ...body.map((l) => `    ${l}`), "}"];
  return {
    stat: byMember((m) => [...byStat(m, (v) => `~ return ${v}`), "~ return 0"]),
    setStat: byMember((m) => [...byStat(m, (v) => `~ ${v} = ${a}`), "~ return"]),
    despawn: byMember((m) => [...(party.present ? [`~ ${party.present}_${m} = 0`] : []), "~ return"]),
    alive: [`~ temp ${c} = 0`, ...inParty([...count, `~ return ${c}`])],
    pick: inParty([
      ...count,
      `{ ${c} <= 0:`, `    ~ return ""`, "}",
      ...extreme("lowest"),
      ...extreme("highest"),
      // One standing member is no choice (and "1d1" is no die).
      "{", `- ${h} == "first" or ${c} == 1:`, `    ~ ${c} = 1`, `- ${h} == "last":`, `    ~ ${c} = ${c}`, `- ${h} == "random":`, `    ~ ${c} = ${n.dice}("1d" + ${c}, "pick:${n.partyKind}")`, "- else:", `    ~ ${c} = 0`, "}",
      `~ return ${n.nthOne}(${k}, ${c})`,
    ]),
    nth: inParty([...nth(a), `~ return ""`]),
    name: byMember((m) => [`~ return ${name(party.members.find((x) => x.id === m)?.name, m)}`]),
  };
}

/**
 * Table rows that spawn (RPG PRD §4.1): `spawn_from(table)` rolls the table, spawns its row and returns the total
 * (so the story can tell it with `table_text`); `spawn_row(table, total)` spawns a total's row and returns how
 * many came. Each entity of a row is spawned by `spawn_row_one` (the template's kind is known, the row's stats
 * set after), `spawn_times` repeats it. Plain ink over `spawn` and `roll`, so nothing new for the engine.
 */
function spawnRowInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const tables = (config.tables ?? []).filter((t) => (t.rows ?? []).some((r) => r.spawn !== undefined));
  if (tables.length === 0) return [];
  const kindOf = new Map((config.kinds ?? []).flatMap((k) => k.templates.map((t) => [t.id, k.id] as const)));
  const tb = n.tableParam, tot = n.totalParam, a = n.amountParam, id = n.tempEntity;
  const count = (r: TableRow) => (typeof r.count === "number" ? String(Math.max(0, Math.floor(r.count))) : r.count !== undefined ? `${n.roll}("${r.count.replace(/["{}]/g, "")}")` : "1");
  const one: string[] = [`=== function ${n.spawnRowOne}(${tb}, ${tot}) ===`, `~ temp ${id} = ""`];
  const row: string[] = [`=== function ${n.spawnRow}(${tb}, ${tot}) ===`];
  for (const t of tables) {
    for (const b of rowBranches(t, n)) {
      const kind = b.row.spawn !== undefined ? kindOf.get(b.row.spawn) : undefined;
      if (kind === undefined) {
        one.push(`{ ${b.cond}:`, `    ~ return ""`, "}");
        row.push(`{ ${b.cond}:`, "    ~ return 0", "}");
        continue;
      }
      one.push(
        `{ ${b.cond}:`,
        `    ~ ${id} = ${n.spawn}("${kind}", "${b.row.spawn}")`,
        ...Object.entries(b.row.stats ?? {}).map(([st, v]) => `    ~ ${n.setStat}(${id}, "${st}", ${v})`),
        `    ~ return ${id}`,
        "}",
      );
      row.push(`{ ${b.cond}:`, `    ~ return ${n.spawnTimes}(${tb}, ${tot}, ${count(b.row)})`, "}");
    }
  }
  one.push(`~ return ""`);
  row.push("~ return 0");
  return [
    "",
    `// Table rows that spawn: ~ temp ${n.tempRowNo} = ${n.spawnFrom}("${tables[0].id}") spawns what the roll's row says and gives the total ({${n.tableText}("${tables[0].id}", ${n.tempRowNo})} tells it).`,
    `=== function ${n.spawnFrom}(${tb}) ===`,
    `~ temp ${n.tempRowNo} = ${n.tableRoll}(${tb})`,
    `~ ${n.spawnRow}(${tb}, ${n.tempRowNo})`,
    `~ return ${n.tempRowNo}`,
    "",
    ...row,
    "",
    ...one,
    "",
    `=== function ${n.spawnTimes}(${tb}, ${tot}, ${a}) ===`,
    `{ ${a} <= 0:`, `    ~ return 0`, "}",
    `~ ${n.spawnRowOne}(${tb}, ${tot})`,
    `~ return 1 + ${n.spawnTimes}(${tb}, ${tot}, ${a} - 1)`,
  ];
}

/**
 * Entities (RPG PRD §4.1): one string VAR per kind holding its entities and a serial counter; the pure EXTERNALs
 * on a store (src/game/entities.ts), and wrappers taking kinds and entity ids as strings. A random pick rolls
 * through the dice EXTERNAL with the label "pick:<kind>", so it follows the run's seed. Without the engine
 * nothing is ever spawned (the fallbacks keep stores empty): the story compiles and runs, but no fight happens.
 */
function entityInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const kinds = config.kinds ?? [];
  const k = n.kindParam, w = n.entityParam, st = n.statParam, a = n.amountParam, h = n.howParam, tp = n.templateParam, s = n.entStoreParam;
  const indent = (lines: string[]) => lines.map((l) => `    ${l}`);
  // A branch per kind, on the kind's name or on the store holding the entity.
  const byKind = (body: (id: string) => string[]) => kinds.flatMap((kd) => [`{ ${k} == "${kd.id}":`, ...indent(body(kd.id)), "}"]);
  const byOwner = (body: (id: string) => string[]) => kinds.flatMap((kd) => [`{ ${n.entHas}(${kd.id}, ${w}):`, ...indent(body(kd.id)), "}"]);
  // The party's members, fixed entities with a VAR per stat (plain ink, so they work without the engine too).
  const party = partyEntity(config);
  const first = kinds[0].id;
  return [
    "",
    `// Entities: ${n.spawn}("${first}", "<template>") gives the new id; ${n.stat}(id, "<stat>"), ${n.setStat}(id, "<stat>", v), ${n.addStat}(id, "<stat>", d),`,
    `// ${n.despawn}(id), ${n.alive}("${first}"), ${n.pickOne}("${first}", "random" | "first" | "last" | "lowest:<stat>" | "highest:<stat>"), ${n.nthOne}("${first}", k), ${n.nameOf}(id).`,
    ...kinds.flatMap((kd) => [`VAR ${kd.id} = ""`, `VAR ${kd.id}${n.serialSuffix} = 0`]),
    `EXTERNAL ${n.entSpawn}(${s}, ${k}, ${tp}, ${w})`,
    `EXTERNAL ${n.entHas}(${s}, ${w})`,
    `EXTERNAL ${n.entGet}(${s}, ${w}, ${st})`,
    `EXTERNAL ${n.entSet}(${s}, ${w}, ${st}, ${a}, ${h})`,
    `EXTERNAL ${n.entDrop}(${s}, ${w})`,
    `EXTERNAL ${n.entCount}(${s})`,
    `EXTERNAL ${n.entAt}(${s}, ${a})`,
    `EXTERNAL ${n.entPick}(${s}, ${h})`,
    `EXTERNAL ${n.entName}(${s}, ${k}, ${w})`,
    "",
    "// Without the engine: nothing is spawned, so every store stays empty.",
    `=== function ${n.entSpawn}(${s}, ${k}, ${tp}, ${w}) ===`, `~ return ${s}`,
    `=== function ${n.entHas}(${s}, ${w}) ===`, "~ return false",
    `=== function ${n.entGet}(${s}, ${w}, ${st}) ===`, "~ return 0",
    `=== function ${n.entSet}(${s}, ${w}, ${st}, ${a}, ${h}) ===`, `~ return ${s}`,
    `=== function ${n.entDrop}(${s}, ${w}) ===`, `~ return ${s}`,
    `=== function ${n.entCount}(${s}) ===`, "~ return 0",
    `=== function ${n.entAt}(${s}, ${a}) ===`, `~ return ""`,
    `=== function ${n.entPick}(${s}, ${h}) ===`, `~ return ""`,
    `=== function ${n.entName}(${s}, ${k}, ${w}) ===`, `~ return ${w}`,
    "",
    // The temps are named like parameters, names reserved for entities, so no id can clash with them.
    `=== function ${n.spawn}(${k}, ${tp}) ===`,
    `~ temp ${n.tempEntity} = ""`,
    ...byKind((id) => [
      `~ ${id}${n.serialSuffix} = ${id}${n.serialSuffix} + 1`,
      `~ ${n.tempEntity} = ${tp} + "_" + ${id}${n.serialSuffix}`,
      `~ ${id} = ${n.entSpawn}(${id}, "${id}", ${tp}, ${n.tempEntity})`,
      `{ ${n.entHas}(${id}, ${n.tempEntity}):`, `    ~ return ${n.tempEntity}`, "}",
    ]),
    `~ return ""`,
    "",
    `=== function ${n.stat}(${w}, ${st}) ===`,
    ...party.stat,
    ...byOwner((id) => [`~ return ${n.entGet}(${id}, ${w}, ${st})`]),
    "~ return 0",
    "",
    `=== function ${n.setStat}(${w}, ${st}, ${a}) ===`,
    ...party.setStat,
    // An entity taken out by its kind's remove stat takes its statuses with it.
    ...byOwner((id) => {
      const remove = kinds.find((x) => x.id === id)?.remove ?? "";
      const gone = config.statuses?.length && remove ? [`{ not ${n.entHas}(${id}, ${w}):`, `    ~ ${n.clearStatus}(${w}, "")`, "}"] : [];
      return [`~ ${id} = ${n.entSet}(${id}, ${w}, ${st}, ${a}, "${remove}")`, ...gone, "~ return"];
    }),
    "",
    `=== function ${n.addStat}(${w}, ${st}, ${a}) ===`,
    `~ ${n.setStat}(${w}, ${st}, ${n.stat}(${w}, ${st}) + ${a})`,
    "",
    `=== function ${n.despawn}(${w}) ===`,
    ...party.despawn,
    ...byOwner((id) => [`~ ${id} = ${n.entDrop}(${id}, ${w})`, ...(config.statuses?.length ? [`~ ${n.clearStatus}(${w}, "")`] : []), "~ return"]),
    "",
    `=== function ${n.alive}(${k}) ===`,
    ...party.alive,
    ...byKind((id) => [`~ return ${n.entCount}(${id})`]),
    "~ return 0",
    "",
    `=== function ${n.pickOne}(${k}, ${h}) ===`,
    `~ temp ${n.tempPickNo} = 0`,
    `~ temp ${n.tempEntity} = ""`,
    ...party.pick,
    // One entity is no choice (and "1d1" is no die): it is the pick, nothing rolled.
    ...byKind((id) => [
      `{ ${h} == "random":`,
      ...indent([
        `~ ${n.tempPickNo} = ${n.entCount}(${id})`,
        `{ ${n.tempPickNo} <= 0:`, `    ~ return ""`, "}",
        `{ ${n.tempPickNo} == 1:`, `    ~ return ${n.entAt}(${id}, 1)`, "}",
        `~ return ${n.entAt}(${id}, ${n.dice}("1d" + ${n.tempPickNo}, "pick:${id}"))`,
      ]),
      "}",
      `~ return ${n.entPick}(${id}, ${h})`,
    ]),
    `~ return ""`,
    "",
    `=== function ${n.nthOne}(${k}, ${a}) ===`,
    `~ temp ${n.tempPickNo} = 0`,
    ...party.nth,
    ...byKind((id) => [`~ return ${n.entAt}(${id}, ${a})`]),
    `~ return ""`,
    "",
    `=== function ${n.nameOf}(${w}) ===`,
    ...party.name,
    ...byOwner((id) => [`~ return ${n.entName}(${id}, "${id}", ${w})`]),
    `~ return ${w}`,
  ];
}

/**
 * Records (solo PRD §4.5): one string VAR per record holding its entries and a counter VAR; the pure
 * EXTERNALs on a store (the engine escapes; the fallback joins with a plain ";"), and wrappers that take the
 * record's id as a string. A pick rolls through the dice EXTERNAL with the label "record:<id>", so it follows the
 * run's seed and shows as a roll; without the engine it reads the whole store.
 */
/** Levels (RPG PRD §4.4): the level, the experience the next one needs, whether it can be taken, taking it. */
function levelInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const lv = config.levels as LevelsDef;
  return [
    "",
    `// Levels by ${lv.resource}: ${n.nextLevelAt}() (0 at the top), ${n.levelUpReady}(), ${n.levelUp}() (gives back whether it went up). What a level gives is the story's.`,
    `VAR ${n.level} = 1`,
    `=== function ${n.nextLevelAt}() ===`,
    ...(lv.at.length > 1 ? [`{ ${n.level}:`, ...lv.at.slice(1).flatMap((need, i) => [`- ${i + 1}:`, `    ~ return ${need}`]), "}"] : []),
    "~ return 0",
    `=== function ${n.levelUpReady}() ===`,
    `~ return ${n.nextLevelAt}() > 0 && ${lv.resource} >= ${n.nextLevelAt}()`,
    `=== function ${n.levelUp}() ===`,
    `{ ${n.levelUpReady}():`, `    ~ ${n.level} = ${n.level} + 1`, "    ~ return true", "}",
    "~ return false",
  ];
}

/** Stacking items (RPG PRD §4.2): a count per item, the item in the inventory while its count is above 0. */
function stackInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const stacks = (config.items ?? []).filter((i) => i.stack);
  const it = n.itemParam, amt = n.amountParam, cnt = (id: string) => `${id}${n.stackSuffix}`;
  const per = (body: (id: string) => string[]) => stacks.flatMap((i) => [`{ ${it} == ${i.id}:`, ...body(i.id).map((l) => `    ${l}`), "}"]);
  return [
    "",
    `// Stacking items: ${n.give}(${stacks[0].id}, 3), ${n.take}(${stacks[0].id}, 1) (gives back how many it took), ${n.invCount}(${stacks[0].id}).`,
    `// An item is in ${n.inventory} while its count is above 0, so {${n.inventory} ? ${stacks[0].id}: …} still works.`,
    ...stacks.map((i) => `VAR ${cnt(i.id)} = 0`),
    `=== function ${n.give}(${it}, ${amt}) ===`,
    `{ ${amt} <= 0:`, "    ~ return", "}",
    ...per((id) => [`~ ${cnt(id)} = ${cnt(id)} + ${amt}`]),
    // Any item, counted or not, is carried after it is given.
    `~ ${n.inventory} += ${it}`,
    `=== function ${n.take}(${it}, ${amt}) ===`,
    `~ temp ${n.tempTaken} = 0`,
    `{ ${amt} <= 0:`, "    ~ return 0", "}",
    ...per((id) => [`~ ${n.tempTaken} = MIN(${amt}, ${cnt(id)})`, `~ ${cnt(id)} = ${cnt(id)} - ${n.tempTaken}`, `{ ${cnt(id)} <= 0:`, `    ~ ${n.inventory} -= ${id}`, "}", `~ return ${n.tempTaken}`]),
    // An item that does not stack: one, if it is carried.
    `{ ${n.inventory} ? ${it}:`, `    ~ ${n.inventory} -= ${it}`, "    ~ return 1", "}",
    "~ return 0",
    `=== function ${n.invCount}(${it}) ===`,
    ...per((id) => [`~ return ${cnt(id)}`]),
    `{ ${n.inventory} ? ${it}:`, "    ~ return 1", "}",
    "~ return 0",
  ];
}

/** Equipment slots (RPG PRD §4.2): the equipped list holds one item per slot; equipping also carries it. */
function slotInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const it = n.itemParam;
  const items = config.items ?? [];
  const lines = [
    "",
    `// Equipment: ${n.equip}(item) wears it (taking off the other item of its slot), ${n.unequip}(item); {${n.equipped} ? item: …}.`,
    `// An item with a slot gives its modifiers only while equipped.`,
    `VAR ${n.equipped} = ()`,
    `=== function ${n.equip}(${it}) ===`,
  ];
  for (const sl of config.slots ?? []) {
    const of = items.filter((i) => i.slot === sl.id).map((i) => i.id);
    if (of.length > 0) lines.push(`{ (${of.join(", ")}) ? ${it}:`, `    ~ ${n.equipped} -= (${of.join(", ")})`, "}");
  }
  lines.push(`~ ${n.inventory} += ${it}`, `~ ${n.equipped} += ${it}`, `=== function ${n.unequip}(${it}) ===`, `~ ${n.equipped} -= ${it}`);
  return lines;
}

/** Status effects (RPG PRD §4.3): one store for everyone, read and written by the engine's pure functions. */
function statusInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const st = n.statusStoreParam, who = n.whoParam, id = n.statusParam, t = n.turnsParam;
  const first = config.statuses?.[0]?.id ?? "poison";
  return [
    "",
    `// Statuses: ${n.addStatus}(who, "${first}", 3) (turns; 0 = until cleared), ${n.hasStatus}(who, "${first}"), ${n.statusTurns}(who, "${first}"),`,
    `// ${n.clearStatus}(who, "${first}") ("" = all of who's), ${n.tickStatuses}() (a turn passes), ${n.restStatuses}() (statuses marked rest end).`,
    `// who is an entity or party member id, or "${n.self}" for the character.`,
    `VAR ${n.statusVar} = ""`,
    `EXTERNAL ${n.stPut}(${st}, ${who}, ${id}, ${t})`,
    `EXTERNAL ${n.stHas}(${st}, ${who}, ${id})`,
    `EXTERNAL ${n.stLeft}(${st}, ${who}, ${id})`,
    `EXTERNAL ${n.stTake}(${st}, ${who}, ${id})`,
    `EXTERNAL ${n.stTick}(${st})`,
    `EXTERNAL ${n.stRest}(${st})`,
    "",
    "// Without the engine nothing takes hold: no one has a status.",
    `=== function ${n.stPut}(${st}, ${who}, ${id}, ${t}) ===`, `~ return ${st}`,
    `=== function ${n.stHas}(${st}, ${who}, ${id}) ===`, "~ return false",
    `=== function ${n.stLeft}(${st}, ${who}, ${id}) ===`, "~ return 0",
    `=== function ${n.stTake}(${st}, ${who}, ${id}) ===`, `~ return ${st}`,
    `=== function ${n.stTick}(${st}) ===`, `~ return ${st}`,
    `=== function ${n.stRest}(${st}) ===`, `~ return ${st}`,
    "",
    `=== function ${n.addStatus}(${who}, ${id}, ${t}) ===`, `~ ${n.statusVar} = ${n.stPut}(${n.statusVar}, ${who}, ${id}, ${t})`,
    `=== function ${n.hasStatus}(${who}, ${id}) ===`, `~ return ${n.stHas}(${n.statusVar}, ${who}, ${id})`,
    `=== function ${n.statusTurns}(${who}, ${id}) ===`, `~ return ${n.stLeft}(${n.statusVar}, ${who}, ${id})`,
    `=== function ${n.clearStatus}(${who}, ${id}) ===`, `~ ${n.statusVar} = ${n.stTake}(${n.statusVar}, ${who}, ${id})`,
    `=== function ${n.tickStatuses}() ===`, `~ ${n.statusVar} = ${n.stTick}(${n.statusVar})`,
    `=== function ${n.restStatuses}() ===`, `~ ${n.statusVar} = ${n.stRest}(${n.statusVar})`,
  ];
}

function recordInk(config: GameConfig): string[] {
  const n = inkNames(config);
  const records = config.records ?? [];
  const r = n.recordParam, e = n.entryParam, st = n.storeParam;
  const per = (body: (id: string, count: string) => string[]) => records.flatMap((rec) => [`{ ${r} == "${rec.id}":`, ...body(rec.id, `${rec.id}${n.countSuffix}`).map((l) => `    ${l}`), "}"]);
  return [
    "",
    `// Records: ${n.recordAdd}("${records[0].id}", "text"), ${n.recordRemove}("${records[0].id}", "text"), ${n.recordCount}("${records[0].id}"),`,
    `// ${n.recordPick}("${records[0].id}") (a random entry, rolled), ${n.recordList}("${records[0].id}") (every entry as text).`,
    ...records.flatMap((rec) => [`VAR ${rec.id} = ""`, `VAR ${rec.id}${n.countSuffix} = 0`]),
    `EXTERNAL ${n.recordJoin}(${st}, ${e})`,
    `EXTERNAL ${n.recordDrop}(${st}, ${e})`,
    `EXTERNAL ${n.recordSize}(${st})`,
    `EXTERNAL ${n.recordAt}(${st}, ${n.recordNoParam})`,
    `EXTERNAL ${n.recordText}(${st})`,
    "",
    "// Without the engine: entries joined with a plain ;, nothing taken out, the whole store read.",
    `=== function ${n.recordJoin}(${st}, ${e}) ===`, `{ ${e} == "":`, `    ~ return ${st}`, "}", `{ ${st} == "":`, `    ~ return ${e}`, "}", `~ return ${st} + ";" + ${e}`,
    `=== function ${n.recordDrop}(${st}, ${e}) ===`, `~ return ${st}`,
    `=== function ${n.recordSize}(${st}) ===`, "~ return 0",
    `=== function ${n.recordAt}(${st}, ${n.recordNoParam}) ===`, `~ return ${st}`,
    `=== function ${n.recordText}(${st}) ===`, `~ return ${st}`,
    "",
    // The counter follows only a store that changed (an empty entry adds nothing). The temp is named like a
    // parameter, a name reserved for records, so no record id can clash with it.
    `=== function ${n.recordAdd}(${r}, ${e}) ===`,
    `~ temp ${st} = ""`,
    ...per((id, count) => [`~ ${st} = ${id}`, `~ ${id} = ${n.recordJoin}(${id}, ${e})`, `{ ${id} != ${st}:`, `    ~ ${count} = ${count} + 1`, "}"]),
    "",
    `=== function ${n.recordRemove}(${r}, ${e}) ===`,
    // One temp for every branch: ink allows a temp to be declared only once in a function.
    `~ temp ${st} = ""`,
    ...per((id, count) => [`~ ${st} = ${id}`, `~ ${id} = ${n.recordDrop}(${id}, ${e})`, `{ ${id} != ${st}:`, `    ~ ${count} = ${count} - 1`, "}"]),
    "",
    `=== function ${n.recordCount}(${r}) ===`,
    ...per((_id, count) => [`~ return ${count}`]),
    "~ return 0",
    "",
    `=== function ${n.recordPick}(${r}) ===`,
    // One entry is no choice (and "1d1" is no die): it is the pick, nothing rolled.
    ...per((id, count) => [`{ ${count} <= 0:`, `    ~ return ""`, "}", `{ ${count} == 1:`, `    ~ return ${n.recordAt}(${id}, 1)`, "}", `~ return ${n.recordAt}(${id}, ${n.dice}("1d" + ${count}, "record:${id}"))`]),
    `~ return ""`,
    "",
    `=== function ${n.recordList}(${r}) ===`,
    ...per((id) => [`~ return ${n.recordText}(${id})`]),
    `~ return ""`,
  ];
}
