import { inkNames, localize, playableCharacters, type GameConfig, type LocalizedText, type TableRow } from "./config";
import { averageFormula, averageRoll, formatFormula } from "./dice";
import { parseRange, tableFormula } from "./tables";

/**
 * The ink a game needs so its stories can run anywhere: skill and resource
 * variables, the character list, a function that loads a character's preset,
 * and a fallback for the engine's check function (no dice: the average roll),
 * so the story also plays in Inky or plain Inkwright. Stories call the check
 * with the skill's name as a string: `check("strength", 12)`. A bilingual game
 * also gets its language variable and text function: `{t("中文", "English")}`.
 */
export function generateInk(config: GameConfig): string {
  const n = inkNames(config);
  const lines: string[] = [
    "// Generated by Inkwright from the game's notes. Do not edit; regenerate.",
    "",
    `LIST ${n.characters} = ${config.characters.map((c) => c.id).join(", ")}`,
    `VAR ${n.current} = ${playableCharacters(config)[0]?.id ?? ""}`,
    "",
    "// Skills of the current character (loaded by " + n.select + ")",
    ...config.skills.map((s) => `VAR ${s.id} = 0`),
    "",
    "// Resources",
    ...config.resources.map((r) => `VAR ${r.id} = ${r.initial}`),
    ...(config.items?.length
      ? ["", "// Items: what the character carries (`~ " + n.inventory + " += " + config.items[0].id + "`, `{" + n.inventory + " ? " + config.items[0].id + ": …}`)",
        `LIST ${n.items} = ${config.items.map((i) => i.id).join(", ")}`, `VAR ${n.inventory} = ()`]
      : []),
    "",
    "// Dice: the engine sets these; saved with the state, so back/load/replay roll the same",
    `VAR ${n.seed} = 0`,
    `VAR ${n.rolls} = 0`,
  ];
  const [first, second] = config.languages ?? [];
  if (first !== undefined && second !== undefined) {
    lines.push(
      "",
      `// Text in the story's language: {${n.textFn}("${first}…", "${second}…")}; the play panel switches ${n.langVar}.`,
      `VAR ${n.langVar} = "${first}"`,
      "",
      `=== function ${n.textFn}(${first}, ${second}) ===`,
      `{ ${n.langVar} == "${second}":`,
      `    ~ return ${second}`,
      "}",
      `~ return ${first}`,
    );
  }
  const companions = config.companionResources ?? [];
  if (companions.length > 0) {
    lines.push("", "// Companions");
    for (const c of config.characters) {
      for (const r of companions) lines.push(`VAR ${r.id}_${c.id} = ${c.companion?.[r.id] ?? r.initial}`);
    }
  }
  const party = config.party;
  if (party) {
    const m0 = party.members[0]?.id ?? "id";
    const gear = config.items?.length ? `, ${n.partyGear}_${m0} its gear (\`~ ${n.partyGear}_${m0} += ${config.items[0].id}\`)` : "";
    lines.push("", `// Party: ${party.stats[0] ? `${party.stats[0].id}_${m0} is a member's ${party.stats[0].id}, ` : ""}${n.partyTitle}_${m0} a line the panel shows under the name${gear}.`);
    for (const m of party.members) {
      for (const st of party.stats) lines.push(`VAR ${st.id}_${m.id} = ${m.stats?.[st.id] ?? 0}`);
      lines.push(`VAR ${n.partyTitle}_${m.id} = ""`);
      if (config.items?.length) lines.push(`VAR ${n.partyGear}_${m.id} = (${(m.items ?? []).join(", ")})`);
    }
  }
  lines.push(
    "",
    `EXTERNAL ${n.check}(${n.skillParam}, ${n.difficultyParam})`,
    "",
    // The id is a string (0.4.0; engines generated before 0.4.0 took a list item and must be
    // regenerated; the panel's "engine out of date" warning flags them).
    `// Loads a character's preset by id: ${n.select}("${playableCharacters(config)[0]?.id ?? "id"}")`,
    `=== function ${n.select}(${n.whoParam}) ===`,
  );
  for (const c of config.characters) {
    lines.push(`{ ${n.whoParam} == "${c.id}":`, `    ~ ${n.current} = ${c.id}`);
    for (const s of config.skills) lines.push(`    ~ ${s.id} = ${c.skills[s.id] ?? 0}`);
    if (config.items?.length) lines.push(`    ~ ${n.inventory} = (${(c.items ?? []).join(", ")})`);
    lines.push("}");
  }
  lines.push("", `// A skill's current level, by name.`, `=== function ${n.skillValue}(${n.skillParam}) ===`);
  for (const s of config.skills) lines.push(`{ ${n.skillParam} == "${s.id}":`, `    ~ return ${s.id}`, "}");
  lines.push("~ return 0");
  const avg = averageRoll(config.rules);
  lines.push(
    "",
    `// Without the engine there are no dice or modifiers: the average roll (${avg}) decides.`,
    `=== function ${n.check}(${n.skillParam}, ${n.difficultyParam}) ===`,
  );
  // Same grading as dice.ts with the average roll: sum systems (and a chaos bag, with its average
  // token) compare the total with the difficulty; roll-under succeeds when the roll is at or under
  // the skill (difficulty unused).
  // Modifier rules live in the engine, so this fallback ignores them: a story played without the
  // engine is a little more forgiving, never different in structure.
  const level = `${n.skillValue}(${n.skillParam})`;
  const wins = config.rules.kind === "rollUnder" ? `${avg} <= ${level}` : `${level} + ${avg} >= ${n.difficultyParam}`;
  lines.push(`{ ${wins}:`, "    ~ return 3", "}", "~ return 1");

  // Free dice and tables: the engine rolls through one EXTERNAL (and shows the faces); the table
  // lookups are plain ink, so the story reads the same row with or without the engine.
  lines.push(
    "",
    `// Dice outside a check: {${n.roll}("2d6+3")} → the total.`,
    `EXTERNAL ${n.dice}(${n.formulaParam}, ${n.labelParam})`,
    "",
    `=== function ${n.roll}(${n.formulaParam}) ===`,
    `~ return ${n.dice}(${n.formulaParam}, "")`,
  );
  const tables = (config.tables ?? []).map((t) => ({ ...t, rows: t.rows ?? [], formula: tableFormula(t) }));
  const averages = new Map<string, number>();
  for (const t of tables) if (t.formula) averages.set(formatFormula(t.formula), averageFormula(t.formula));
  lines.push("", "// Without the engine the dice are flat: each table's average, 1 for anything else.", `=== function ${n.dice}(${n.formulaParam}, ${n.labelParam}) ===`);
  for (const [text, avg] of averages) lines.push(`{ ${n.formulaParam} == "${text}":`, `    ~ return ${avg}`, "}");
  lines.push("~ return 1");
  if (tables.length > 0) {
    const text = (t: LocalizedText) => {
      const esc = (x: string) => x.replace(/["{}]/g, (c) => (c === '"' ? "'" : c === "{" ? "(" : ")")).replace(/\s+/g, " ");
      return first !== undefined && second !== undefined
        ? `${n.textFn}("${esc(localize(t, first, ""))}", "${esc(localize(t, second, ""))}")`
        : `"${esc(localize(t, "", ""))}"`;
    };
    lines.push(
      "",
      `// Tables: {${n.table}("${tables[0].id}")} rolls and reads a row; ${n.tableRoll}(${n.tableParam}) is the total alone, ${n.tableText}/${n.tableId}(${n.tableParam}, ${n.totalParam}) look a total up.`,
      `=== function ${n.tableRoll}(${n.tableParam}) ===`,
    );
    for (const t of tables) lines.push(`{ ${n.tableParam} == "${t.id}":`, `    ~ return ${n.dice}("${t.formula ? formatFormula(t.formula) : "1d1"}", "${t.id}")`, "}");
    lines.push("~ return 0");
    const lookups: [string, (r: TableRow) => string][] = [[n.tableText, (r) => text(r.text)], [n.tableId, (r) => `"${(r.id ?? "").replace(/["{}]/g, "")}"`]];
    for (const [fn, value] of lookups) {
      lines.push("", `=== function ${fn}(${n.tableParam}, ${n.totalParam}) ===`);
      for (const t of tables) {
        // Rows with ranges are read in ascending order (`total <= hi`); without, the total is the row number. The last row catches the rest.
        const ranged = t.rows.some((r) => parseRange(r.range) !== null);
        // Tie-safe: two open bottoms (`≤N`) both start at -Infinity, and a subtraction of those is NaN.
        const lo = (r: TableRow) => parseRange(r.range)?.lo ?? 0;
        const rows = ranged ? [...t.rows].sort((a, b) => (lo(a) < lo(b) ? -1 : lo(a) > lo(b) ? 1 : 0)) : t.rows;
        rows.forEach((r, i) => {
          // An open top (`6+`) can only be the last row, which takes the rest anyway.
          const last = i === rows.length - 1 || parseRange(r.range)?.hi === Infinity;
          const cond = last ? "" : ranged ? ` and ${n.totalParam} <= ${parseRange(r.range)?.hi ?? 0}` : ` and ${n.totalParam} == ${i + 1}`;
          lines.push(`{ ${n.tableParam} == "${t.id}"${cond}:`, `    ~ return ${value(r)}`, "}");
        });
      }
      lines.push(`~ return ""`);
    }
    lines.push("", `=== function ${n.table}(${n.tableParam}) ===`, `~ return ${n.tableText}(${n.tableParam}, ${n.tableRoll}(${n.tableParam}))`);
  }

  // Decks: one LIST per deck and a VAR holding the pile; the engine picks the card's position with
  // the same seeded dice (the count goes along as the formula), the ink takes that card out.
  const decks = config.decks ?? [];
  if (decks.length > 0) {
    const first = decks[0];
    lines.push("", `// Decks: ${n.draw}("${first.id}") takes a random card out of the pile (an empty list once none is left); ${n.shuffle} puts them all back; ${n.deckLeft} counts the pile. A hand is a list the story keeps (declared under hands to show as cards): ~ hand += ${n.draw}("${first.id}").`);
    for (const d of decks) {
      const ids = d.cards.map((c) => c.id).join(", ");
      lines.push(`LIST ${d.id} = ${ids}`, `VAR ${d.id}${n.pileSuffix} = (${ids})`);
    }
    lines.push(
      "", "// The k-th card of a list, lowest first.",
      `=== function ${n.nthCard}(${n.stackParam}, ${n.kParam}) ===`,
      `~ temp c = LIST_MIN(${n.stackParam})`,
      `{ ${n.kParam} <= 1 or LIST_COUNT(${n.stackParam}) <= 1:`, "    ~ return c", "}",
      `~ return ${n.nthCard}(${n.stackParam} - c, ${n.kParam} - 1)`,
      "", `=== function ${n.draw}(${n.deckParam}) ===`,
    );
    for (const d of decks) {
      const pile = `${d.id}${n.pileSuffix}`;
      lines.push(
        `{ ${n.deckParam} == "${d.id}" and LIST_COUNT(${pile}) > 0:`,
        `    ~ temp c = ${n.nthCard}(${pile}, ${n.dice}(LIST_COUNT(${pile}), "${d.id}"))`,
        `    ~ ${pile} -= c`, "    ~ return c", "}",
      );
    }
    lines.push("~ temp none = ()", "~ return none", "", `=== function ${n.shuffle}(${n.deckParam}) ===`);
    for (const d of decks) lines.push(`{ ${n.deckParam} == "${d.id}":`, `    ~ ${d.id}${n.pileSuffix} = LIST_ALL(${d.id})`, "}");
    lines.push("", `=== function ${n.deckLeft}(${n.deckParam}) ===`);
    for (const d of decks) lines.push(`{ ${n.deckParam} == "${d.id}":`, `    ~ return LIST_COUNT(${d.id}${n.pileSuffix})`, "}");
    lines.push("~ return 0");
    // Card attributes: one function per key, giving the number on a card (0 when it has none).
    const keys = [...new Set(decks.flatMap((d) => d.cards.flatMap((c) => Object.keys(c.attrs ?? {}))))];
    if (keys.length > 0) {
      lines.push("", `// Card attributes: ${n.cardPrefix}${keys[0]}(${n.cardParam}) is that number on the card (0 when it has none).`);
      for (const key of keys) {
        lines.push(`=== function ${n.cardPrefix}${key}(${n.cardParam}) ===`);
        for (const d of decks) {
          for (const c of d.cards) {
            const v = c.attrs?.[key];
            if (v !== undefined) lines.push(`{ ${n.cardParam} == ${c.id}:`, `    ~ return ${v}`, "}");
          }
        }
        lines.push("~ return 0");
      }
    }
  }
  // Hands: the panel shows each as a row of cards; a choice tagged `#play:<hand>` is taken with one
  // of them, which the engine writes into the played VAR first.
  const hands = config.hands ?? [];
  if (hands.length > 0) {
    lines.push("", `// Hands: shown as cards in the panel; the story fills them (~ ${hands[0].id} += ${n.draw}("…")). A choice tagged #play:${hands[0].id} puts the card the player picked into ${n.played} before the choice runs: ~ ${hands[0].id} -= ${n.played}.`);
    for (const h of hands) lines.push(`VAR ${h.id} = ()`);
    lines.push(`VAR ${n.played} = ()`);
  }
  // Map: the places as a LIST, where the player is, which places are revealed, and each token's place.
  const map = config.map;
  if (map && map.places.length > 0) {
    const shown = map.places.filter((p) => !p.hidden).map((p) => p.id);
    lines.push("", `// Map: ${n.here} is where the player stands (~ ${n.here} = ${map.places[0].id}), ${n.revealed} the places shown (~ ${n.revealed} += …); a token's place is its own VAR (an empty list keeps it off the map).`);
    lines.push(`LIST ${n.places} = ${map.places.map((p) => p.id).join(", ")}`);
    lines.push(`VAR ${n.here} = (${shown[0] ?? ""})`);
    lines.push(`VAR ${n.revealed} = (${shown.join(", ")})`);
    for (const t of map.tokens ?? []) lines.push(`VAR ${t.id}${n.atSuffix} = (${t.at ?? ""})`);
  }
  const dungeon = config.dungeon;
  if (dungeon) {
    // The generator is handed the resolved config (shapes read from `from` are in), but the comment must not name a shape that is not there.
    const first = dungeon.shapes[0]?.id ?? "<shape id>";
    lines.push(
      "",
      `// Growing dungeon: ${n.dungeonVar} holds the layout (rooms and used doors) as text, ${n.dungeonRoom} the room the party is in.`,
      `// ${n.beginDungeon}("${first}") draws the first room; ${n.addRoom}("${first}", room, door) hangs a room of that shape on the door-th free door of a room`,
      `// (room 0 = any room) and returns its number, or 0 when the door led into a wall; ${n.markRoom}(room, "text") writes a note on a room.`,
      `// ${n.dungeonDoors}(${n.dungeonVar}, room) counts the free doors left (room 0 = the whole dungeon), ${n.dungeonRooms}(${n.dungeonVar}) the rooms, ${n.dungeonShape}/${n.dungeonCorridor}(${n.dungeonVar}, room) read a room.`,
      `VAR ${n.dungeonVar} = ""`,
      `VAR ${n.dungeonRoom} = 0`,
      `EXTERNAL ${n.dungeonStart}(${n.shapeParam})`,
      `EXTERNAL ${n.dungeonAdd}(${n.layoutParam}, ${n.shapeParam}, ${n.roomParam}, ${n.doorParam})`,
      `EXTERNAL ${n.dungeonRooms}(${n.layoutParam})`,
      `EXTERNAL ${n.dungeonDoors}(${n.layoutParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonMark}(${n.layoutParam}, ${n.roomParam}, ${n.markParam})`,
      `EXTERNAL ${n.dungeonShape}(${n.layoutParam}, ${n.roomParam})`,
      `EXTERNAL ${n.dungeonCorridor}(${n.layoutParam}, ${n.roomParam})`,
      "",
      "// Without the engine nothing grows: no rooms, no doors left.",
      `=== function ${n.dungeonStart}(${n.shapeParam}) ===`, `~ return ""`,
      `=== function ${n.dungeonAdd}(${n.layoutParam}, ${n.shapeParam}, ${n.roomParam}, ${n.doorParam}) ===`, `~ return ${n.layoutParam}`,
      `=== function ${n.dungeonRooms}(${n.layoutParam}) ===`, "~ return 0",
      `=== function ${n.dungeonDoors}(${n.layoutParam}, ${n.roomParam}) ===`, "~ return 0",
      `=== function ${n.dungeonMark}(${n.layoutParam}, ${n.roomParam}, ${n.markParam}) ===`, `~ return ${n.layoutParam}`,
      `=== function ${n.dungeonShape}(${n.layoutParam}, ${n.roomParam}) ===`, `~ return ""`,
      `=== function ${n.dungeonCorridor}(${n.layoutParam}, ${n.roomParam}) ===`, "~ return 0",
      "",
      `=== function ${n.beginDungeon}(${n.shapeParam}) ===`,
      `~ ${n.dungeonVar} = ${n.dungeonStart}(${n.shapeParam})`,
      `~ ${n.dungeonRoom} = ${n.dungeonRooms}(${n.dungeonVar})`,
      `~ return ${n.dungeonRoom}`,
      "",
      `=== function ${n.addRoom}(${n.shapeParam}, ${n.roomParam}, ${n.doorParam}) ===`,
      `~ temp before = ${n.dungeonRooms}(${n.dungeonVar})`,
      `~ ${n.dungeonVar} = ${n.dungeonAdd}(${n.dungeonVar}, ${n.shapeParam}, ${n.roomParam}, ${n.doorParam})`,
      `{ ${n.dungeonRooms}(${n.dungeonVar}) > before:`, `    ~ return ${n.dungeonRooms}(${n.dungeonVar})`, "}",
      "~ return 0",
      "",
      `=== function ${n.markRoom}(${n.roomParam}, ${n.markParam}) ===`,
      `~ ${n.dungeonVar} = ${n.dungeonMark}(${n.dungeonVar}, ${n.roomParam}, ${n.markParam})`,
    );
  }
  return lines.join("\n") + "\n";
}
